const $ = (id) => document.getElementById(id);
const state = { lang: "en", history: [], busy: false, status: "ready", recording: null, audio: null, speakToken: 0, count: 0 };
try { const s = localStorage.getItem("lang"); if (s in I18N) state.lang = s; } catch (e) {}
const t = (k) => I18N[state.lang][k] ?? I18N.en[k];
const clock = () => new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" });

/* ---------- text + status ---------- */
function applyText() {
  document.documentElement.lang = state.lang;
  document.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  $("input").placeholder = t("placeholder");
  $("send").textContent = t("send");
  setStatus(state.status);
}

function setStatus(s) {
  state.status = s;
  $("station").dataset.status = s;
  $("pillText").textContent = t("st_" + s);
  const hint = { ready: "hint_ready", listening: "hint_listening", speaking: "hint_speaking" }[s] || "hint_working";
  $("hint").textContent = t(hint);
  $("timerLabel").textContent = s === "ready" ? t("timerReady") : t("st_" + s);
  $("stopVoice").hidden = s !== "speaking";
  const step = { ready: 1, listening: 1, understanding: 2, thinking: 3, speaking: 4 }[s];
  document.querySelectorAll("#steps li").forEach((li, i) => li.classList.toggle("on", i + 1 === step));
  $("mic").disabled = s === "understanding" || s === "thinking";
  $("mic").setAttribute("aria-pressed", s === "listening");
}

function renderLangs() {
  $("langs").innerHTML = "";
  Object.entries(I18N).forEach(([code, l]) => {
    const b = document.createElement("button");
    b.className = "pillbtn"; b.type = "button"; b.textContent = l.name;
    b.setAttribute("role", "radio"); b.setAttribute("aria-checked", code === state.lang);
    b.onclick = () => setLang(code);
    $("langs").appendChild(b);
  });
}

function setLang(code) {
  state.lang = code;
  try { localStorage.setItem("lang", code); } catch (e) {}
  stopAudio(); renderLangs(); applyText();
  if (!state.history.length) { $("thread").innerHTML = ""; addMsg("bot", t("greeting"), { speak: true }); }
}

/* ---------- session ---------- */
function newSession() {
  stopAudio();
  state.history = []; state.count = 0;
  $("thread").innerHTML = "";
  $("mSession").textContent = [...crypto.getRandomValues(new Uint8Array(4))].map((b) => b.toString(16).padStart(2, "0")).join("");
  $("mStarted").textContent = clock();
  $("mCount").textContent = "0"; $("mVoice").textContent = "-";
  $("timer").textContent = "00:00";
  setStatus("ready");
  addMsg("bot", t("greeting"), { speak: true });
}

/* ---------- messages ---------- */
const PLAY = '<svg viewBox="0 0 24 24"><path d="M8 5v14l11-7z" fill="currentColor"/></svg>';

function addMsg(role, text, opts = {}) {
  const m = document.createElement("div");
  m.className = `msg ${role}`;
  const head = document.createElement("div");
  head.className = "msg-head";
  const badge = document.createElement("span");
  badge.className = "badge";
  badge.textContent = role === "user" ? t("patient") : "MediGuide";
  const stamp = document.createElement("span");
  stamp.className = "stamp"; stamp.textContent = clock();
  head.append(badge, stamp);
  const p = document.createElement("p");
  p.textContent = text;
  m.append(head, p);
  if (role === "bot" && opts.speak) {
    const b = document.createElement("button");
    b.className = "replay"; b.type = "button"; b.innerHTML = `${PLAY}<span>${t("listen")}</span>`;
    b.onclick = () => speak(text);
    m.appendChild(b);
  }
  $("thread").appendChild(m);
  $("thread").scrollTop = $("thread").scrollHeight;
  return m;
}

function addThinking() {
  const m = document.createElement("div");
  m.className = "msg bot";
  m.innerHTML = '<div class="msg-head"><span class="badge">MediGuide</span></div><span class="dots"><i></i><i></i><i></i></span>';
  $("thread").appendChild(m);
  $("thread").scrollTop = $("thread").scrollHeight;
  return m;
}

/* ---------- API ---------- */
async function api(path, options) {
  const r = await fetch(path, options);
  if (!r.ok) {
    let msg = t("error");
    try { msg = (await r.json()).error || msg; } catch (e) {}
    throw new Error(msg);
  }
  return r;
}

async function send(text) {
  text = (text || "").trim();
  if (!text || state.busy) return;
  state.busy = true; $("send").disabled = true;
  stopAudio();
  addMsg("user", text);
  $("input").value = "";
  $("mCount").textContent = ++state.count;
  setStatus("thinking");
  const thinking = addThinking();
  const prior = state.history.slice();
  state.history.push({ role: "user", content: text });
  try {
    const r = await api("/api/chat", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ message: text, language: state.lang, history: prior }),
    });
    const { reply } = await r.json();
    thinking.remove();
    state.history.push({ role: "assistant", content: reply });
    addMsg("bot", reply, { speak: true });
    if ($("autospeak").checked) speak(reply); else setStatus("ready");
  } catch (e) {
    thinking.remove(); state.history.pop();
    addMsg("error", e.message); setStatus("ready");
  } finally {
    state.busy = false; $("send").disabled = false;
  }
}

/* ---------- speech out ---------- */
function stopAudio() {
  state.speakToken++;
  if (state.audio) { state.audio.pause(); state.audio = null; }
  if (state.status === "speaking") setStatus("ready");
}

async function speak(text) {
  stopAudio();
  const token = state.speakToken;
  setStatus("speaking");
  try {
    const r = await api("/api/tts", {
      method: "POST", headers: { "Content-Type": "application/json" },
      body: JSON.stringify({ text, language: state.lang }),
    });
    const voice = r.headers.get("X-Voice");
    if (voice) $("mVoice").textContent = voice;
    const blob = await r.blob();
    if (token !== state.speakToken) return;
    const url = URL.createObjectURL(blob);
    const a = new Audio(url);
    state.audio = a;
    a.onended = () => { URL.revokeObjectURL(url); if (state.audio === a) { state.audio = null; setStatus("ready"); } };
    await a.play();
  } catch (e) {
    if (token === state.speakToken) { addMsg("error", e.message); setStatus("ready"); }
  }
}

/* ---------- speech in ---------- */
function fmt(s) { return String(Math.floor(s / 60)).padStart(2, "0") + ":" + String(s % 60).padStart(2, "0"); }

function startMeter(stream) {
  const AC = window.AudioContext || window.webkitAudioContext;
  const ac = new AC(), an = ac.createAnalyser();
  an.fftSize = 64;
  ac.createMediaStreamSource(stream).connect(an);
  const data = new Uint8Array(an.frequencyBinCount), bars = [...document.querySelectorAll(".wave i")];
  const m = { ac, raf: 0 };
  (function loop() {
    an.getByteFrequencyData(data);
    bars.forEach((b, i) => (b.style.height = 6 + (data[i + 1] / 255) * 24 + "px"));
    m.raf = requestAnimationFrame(loop);
  })();
  return m;
}

function stopMeter(m) {
  cancelAnimationFrame(m.raf); m.ac.close();
  document.querySelectorAll(".wave i").forEach((b) => (b.style.height = ""));
}

async function toggleMic() {
  if (state.recording) return stopRecording();
  stopAudio();
  try {
    const stream = await navigator.mediaDevices.getUserMedia({ audio: true });
    const rec = new MediaRecorder(stream), chunks = [];
    rec.ondataavailable = (e) => chunks.push(e.data);
    rec.onstop = () => { stream.getTracks().forEach((x) => x.stop()); handleRecording(new Blob(chunks)); };
    const meter = startMeter(stream), t0 = Date.now();
    const tick = setInterval(() => ($("timer").textContent = fmt(Math.floor((Date.now() - t0) / 1000))), 250);
    state.recording = { rec, meter, tick };
    rec.start();
    setStatus("listening");
  } catch (e) {
    addMsg("error", t("micDenied"));
  }
}

function stopRecording() {
  const { rec, meter, tick } = state.recording;
  state.recording = null;
  clearInterval(tick); stopMeter(meter);
  setStatus("understanding");
  rec.stop();
}

async function handleRecording(blob) {
  try {
    const wav = await blobToWav(blob);
    const fd = new FormData();
    fd.append("file", wav, "speech.wav");
    const r = await api("/api/transcribe", { method: "POST", body: fd });
    const { text } = await r.json();
    if (text) return send(text);
    addMsg("error", t("noSpeech"));
  } catch (e) {
    addMsg("error", e.message);
  }
  setStatus("ready");
}

async function blobToWav(blob) {
  const ctx = new (window.AudioContext || window.webkitAudioContext)();
  const decoded = await ctx.decodeAudioData(await blob.arrayBuffer());
  ctx.close();
  const off = new OfflineAudioContext(1, Math.max(1, Math.ceil(decoded.duration * 16000)), 16000);
  const src = off.createBufferSource();
  src.buffer = decoded; src.connect(off.destination); src.start();
  return encodeWav((await off.startRendering()).getChannelData(0), 16000);
}

function encodeWav(samples, rate) {
  const buf = new ArrayBuffer(44 + samples.length * 2), v = new DataView(buf);
  const str = (o, s) => [...s].forEach((c, i) => v.setUint8(o + i, c.charCodeAt(0)));
  str(0, "RIFF"); v.setUint32(4, 36 + samples.length * 2, true); str(8, "WAVEfmt ");
  v.setUint32(16, 16, true); v.setUint16(20, 1, true); v.setUint16(22, 1, true);
  v.setUint32(24, rate, true); v.setUint32(28, rate * 2, true); v.setUint16(32, 2, true); v.setUint16(34, 16, true);
  str(36, "data"); v.setUint32(40, samples.length * 2, true);
  samples.forEach((s, i) => { const c = Math.max(-1, Math.min(1, s)); v.setInt16(44 + i * 2, c < 0 ? c * 0x8000 : c * 0x7fff, true); });
  return new Blob([v], { type: "audio/wav" });
}

